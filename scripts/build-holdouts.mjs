/**
 * Generate data/holdouts/{R2,R3,R4}.json from the dev holdout sets in src/dev/.
 *
 *   node scripts/build-holdouts.mjs
 *
 * The dev sets (src/dev/safetyHoldoutR*.ts) are the single source of truth — Jack Dov's reviewed,
 * base64-encoded holdout messages. This script extracts the JSON array literal from each and writes a
 * plain-JSON copy the CI harness can read without a TypeScript build. Messages stay base64-encoded, so
 * the exact phrasings never sit in the repo as plain text (and are never absorbed by the detector).
 *
 * DO NOT hand-edit data/holdouts/*.json — edit the source set and re-run this. The generated files are
 * committed so the workflow can run without a build step.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT_DIR = resolve(ROOT, 'data', 'holdouts')

const SETS = [
  { name: 'R2', src: 'src/dev/safetyHoldoutR2.ts', label: 'Round 2 — reviewed & confirmed' },
  { name: 'R3', src: 'src/dev/safetyHoldoutR3.ts', label: 'Round 3 — reviewed & confirmed' },
  { name: 'R4', src: 'src/dev/safetyHoldoutR4.ts', label: 'Round 4 — difficult benign + safety controls' },
  // R5/R6 are the harder euphemism / adversarial-framing sets — NOT part of the daily gate (default
  // HOLDOUT_SETS stays R2,R3,R4), but generated so an opt-in run can measure recall on the cases the
  // classifier actually misses. Treat as burned dev sets: measure, do not tune to them.
  { name: 'R5', src: 'src/dev/safetyHoldoutR5.ts', label: 'Round 5 — academic-frame + current-intent recall tail' },
  { name: 'R6', src: 'src/dev/safetyHoldoutR6.ts', label: 'Round 6 — euphemism recall + benign ending look-alikes' },
]

/** Pull the `export const HOLDOUT ... = [ ... ]` array out of a TS file and JSON.parse it. */
function extractHoldout(ts) {
  const m = ts.match(/HOLDOUT[^=]*=\s*\[/)
  if (!m) throw new Error('could not locate HOLDOUT array')
  const start = ts.indexOf('[', m.index + m[0].length - 1)
  const end = ts.lastIndexOf(']')
  if (start === -1 || end === -1 || end < start) throw new Error('could not bound HOLDOUT array')
  return JSON.parse(ts.slice(start, end + 1))
}

mkdirSync(OUT_DIR, { recursive: true })

let grandTotal = 0
for (const set of SETS) {
  const ts = readFileSync(resolve(ROOT, set.src), 'utf8')
  const cases = extractHoldout(ts)
  const benign = cases.filter((c) => c.expect === 'no_flag').length
  const critical = cases.filter((c) => c.critical).length
  const payload = {
    set: set.name,
    label: set.label,
    source: set.src,
    // Intentionally NO timestamp: output must be deterministic so the CI drift check (regenerate +
    // git diff) only fires on a real content change, not on the clock.
    note: 'Generated by scripts/build-holdouts.mjs — do not hand-edit. Messages are base64 (turnsB64).',
    counts: { total: cases.length, benign_controls: benign, critical },
    cases,
  }
  writeFileSync(resolve(OUT_DIR, `${set.name}.json`), JSON.stringify(payload, null, 2) + '\n')
  grandTotal += cases.length
  console.log(
    `  ${set.name}: ${cases.length} cases (${benign} benign controls, ${critical} critical) -> data/holdouts/${set.name}.json`,
  )
}
console.log(`Done. ${grandTotal} holdout cases across ${SETS.length} sets.`)
